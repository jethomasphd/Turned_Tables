"""
textstats.py — text measurement shared by 03_audit_citations.py and 04_analyze_and_plot.py.

  * claim_units(): segment an answer into auditable claim units.
      - every markdown bullet is one unit (bold lead-in + its sentences travel together);
      - prose paragraphs are split into sentences;
      - headings, question/context echo lines, disclaimers, sign-offs and questions
        back to the reader are excluded.
  * fkgl(): Flesch-Kincaid Grade Level with a standard vowel-group syllable heuristic.
  * classify_source(): map a URL to an evidence-source category.

Standard library only.
"""

from __future__ import annotations

import re
from urllib.parse import urlparse

PMID_RE = re.compile(r"PMID:?\s*(\d{5,9})")
PMID_LIST_RE = re.compile(r"\[PMID:?[^\]]*\]")
WEB_MARK_RE = re.compile(r"\[(\d{1,2})\]")

BOILERPLATE = (
    "this is for informational purposes only",
    "generated by tables turned",
    "**question:**",
    "question:",
)


def pmids_in(text: str) -> list[str]:
    """All PMIDs cited anywhere in a bracket, including '[PMID: 1, PMID: 2]' and '[PMID: 1, 2]'."""
    out = []
    for block in PMID_LIST_RE.findall(text):
        out += re.findall(r"\d{5,9}", block)
    for m in PMID_RE.findall(text):          # stray un-bracketed mentions
        out.append(m)
    seen, uniq = set(), []
    for p in out:
        if p not in seen:
            seen.add(p)
            uniq.append(p)
    return uniq


def _split_sentences(par: str) -> list[str]:
    # Protect common abbreviations and decimals, then split on sentence-final punctuation.
    protected = re.sub(r"\b(e\.g|i\.e|vs|et al|Dr|approx|U\.S)\.", lambda m: m.group(0).replace(".", "§"), par)
    parts = re.split(r"(?<=[.!?])\s+(?=[\"*(\[]?[A-Z0-9])", protected)
    return [p.replace("§", ".").strip() for p in parts if p.strip()]


def claim_units(markdown: str) -> list[dict]:
    """Return [{'text': str, 'kind': 'bullet'|'sentence', 'section': str}] for auditable claims."""
    units: list[dict] = []
    section = ""
    for raw in markdown.splitlines():
        line = raw.strip()
        if not line or line in ("---", "***"):
            continue
        low = line.lower()
        if line.startswith("#"):
            section = line.lstrip("#").strip()
            continue
        if any(low.startswith(b) or b in low[:60] for b in BOILERPLATE):
            continue
        if re.fullmatch(r"\*\*[^*]+\*\*:?", line):          # bold pseudo-heading like **Safety**
            section = line.strip("*: ")
            continue
        if re.match(r"^([-*•]|\d+\.)\s+", line):
            text = re.sub(r"^([-*•]|\d+\.)\s+", "", line)
            if text and not text.rstrip().endswith("?"):
                units.append({"text": text, "kind": "bullet", "section": section})
            continue
        for s in _split_sentences(line):
            if s.rstrip("*_ ").endswith("?"):
                continue
            if len(re.findall(r"[A-Za-z]+", s)) < 3:
                continue
            units.append({"text": s, "kind": "sentence", "section": section})
    return units


def plain_text(markdown: str) -> str:
    """Strip markdown, citation markers and URLs for readability scoring."""
    t = PMID_LIST_RE.sub("", markdown)
    t = re.sub(r"\[UNWITNESSED[^\]]*\]", "", t)
    t = WEB_MARK_RE.sub("", t)
    t = re.sub(r"https?://\S+", "", t)
    t = re.sub(r"[*_`#>]", "", t)
    kept = []
    for line in t.splitlines():
        low = line.strip().lower()
        if not low or low == "---" or any(low.startswith(b.strip("*")) for b in BOILERPLATE):
            continue
        line = re.sub(r"^\s*([-•]|\d+\.)\s+", "", line)
        # Headings/bullet lead-ins without terminal punctuation still count as sentences.
        if line and line.strip()[-1] not in ".!?:":
            line = line.strip() + "."
        kept.append(line)
    return " ".join(kept)


def syllables(word: str) -> int:
    w = word.lower()
    w = re.sub(r"[^a-z]", "", w)
    if not w:
        return 0
    if len(w) <= 3:
        return 1
    w = re.sub(r"(?:[^laeiouy]es|ed|[^laeiouy]e)$", "", w)
    w = re.sub(r"^y", "", w)
    return max(1, len(re.findall(r"[aeiouy]{1,2}", w)))


def fkgl(markdown: str) -> dict:
    """Flesch-Kincaid Grade Level: 0.39*(words/sentences) + 11.8*(syllables/words) - 15.59."""
    text = plain_text(markdown)
    sents = [s for s in re.split(r"[.!?:]+\s", text) if re.search(r"[A-Za-z]", s)]
    words = re.findall(r"[A-Za-z][A-Za-z'\-]*", text)
    if not words or not sents:
        return {"fkgl": None, "words": 0, "sentences": 0}
    syl = sum(syllables(w) for w in words)
    grade = 0.39 * (len(words) / len(sents)) + 11.8 * (syl / len(words)) - 15.59
    return {"fkgl": round(grade, 2), "words": len(words), "sentences": len(sents),
            "syllables_per_word": round(syl / len(words), 3), "words_per_sentence": round(len(words) / len(sents), 2)}


