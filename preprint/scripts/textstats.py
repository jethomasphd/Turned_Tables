def _hit(host: str, full: str, entries: tuple) -> bool:
    for e in entries:
        if "/" in e:
            if e in full:
                return True
        elif e.startswith("."):
            if host.endswith(e):
                return True
        elif e.endswith(".") or "." not in e:
            if e in host:
                return True
        elif host == e or host.endswith("." + e):
            return True
    return False


def classify_source(url: str) -> str:
    """Rule-based mapping from URL to one of SOURCE_CLASSES (first match wins, literature first)."""
    u = url.lower()
    parsed = urlparse(u)
    host = parsed.netloc.split(":")[0]
    host = host[4:] if host.startswith("www.") else host
    full = host + parsed.path
    if _hit(host, full, _LIT):
        return "Peer-reviewed literature"
    if _hit(host, full, _COMM):
        return "Commercial / retail"
    if _hit(host, full, _MEDIA):
        return "Health media & nonprofits"
    if _hit(host, full, _SOC):
        return "Professional society"
    if _hit(host, full, _GOV):
        return "Government / public health"
    if host.startswith("sites.") or host.startswith("blogs."):     # personal/course blogs on .edu hosts
        return "News & other"
    if _hit(host, full, _ACAD):
        return "Academic / hospital"
    return "News & other"
